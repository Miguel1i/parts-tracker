import { describe, expect, it } from "vitest";
import { catalogKey, hostOf, parsePcpp, pcppQuery, slugText } from "./index";

describe("parsePcpp", () => {
  it("reads a Markdown list", () => {
    const md = [
      "Type | Item | Price",
      ":--- | :--- | ---:",
      "**CPU** | [AMD Ryzen 7 9800X3D 4.7 GHz 8-Core Processor](https://pcpartpicker.com/product/abc/amd-ryzen-7-9800x3d) | € 449,00",
      "**Memory** | [G.Skill Flare X5 32 GB (2 x 16 GB) DDR5-6000 CL30 Memory](https://pcpartpicker.com/product/def) | €129.99",
      "| _Video Card_ | [Sapphire Pulse RX 9070 XT](https://pcpartpicker.com/product/ghi) | $599.99 @ Amazon | [Buy](https://x.test/buy) |",
      "",
      "| | Total | €1.200,00 |",
      "*Generated by [PCPartPicker](https://pcpartpicker.com) 2026-01-01*",
    ].join("\n");
    expect(parsePcpp(md)).toEqual([
      {
        category: "CPU",
        name: "AMD Ryzen 7 9800X3D 4.7 GHz 8-Core Processor",
        priceEur: 449,
        url: "https://pcpartpicker.com/product/abc/amd-ryzen-7-9800x3d",
      },
      {
        category: "Memory",
        name: "G.Skill Flare X5 32 GB (2 x 16 GB) DDR5-6000 CL30 Memory",
        priceEur: 129.99,
        url: "https://pcpartpicker.com/product/def",
      },
      {
        category: "Video Card",
        name: "Sapphire Pulse RX 9070 XT",
        priceEur: null, // $ price is not converted
        url: "https://pcpartpicker.com/product/ghi",
      },
    ]);
  });

  it("reads plain text and copied tables", () => {
    const text = [
      "Your build",
      "",
      "CPU: AMD Ryzen 7 9800X3D 4.7 GHz 8-Core Processor €449,00 Buy",
      "CPU Cooler  Thermalright Peerless Assassin 120 SE (€ 1.234,50)",
      "Storage Samsung 990 Pro 2 TB M.2-2280 NVMe $169.99 Buy",
      "Banana smoothie 3,00 €",
      "Case",
      "Total: €1.900,00",
      "Generated by PCPartPicker",
    ].join("\n");
    expect(parsePcpp(text)).toEqual([
      { category: "CPU", name: "AMD Ryzen 7 9800X3D 4.7 GHz 8-Core Processor", priceEur: 449 },
      { category: "CPU Cooler", name: "Thermalright Peerless Assassin 120 SE", priceEur: 1234.5 },
      { category: "Storage", name: "Samsung 990 Pro 2 TB M.2-2280 NVMe", priceEur: null },
    ]);
  });

  it("returns nothing for empty or unrelated text", () => {
    expect(parsePcpp("")).toEqual([]);
    expect(parsePcpp("hello\nworld")).toEqual([]);
  });
});

describe("pcppQuery", () => {
  it.each([
    ["AMD Ryzen 7 9800X3D 4.7 GHz 8-Core Processor", "AMD Ryzen 7 9800X3D"],
    [
      "G.Skill Flare X5 32 GB (2 x 16 GB) DDR5-6000 CL30 Memory",
      "G.Skill Flare X5 32GB DDR5-6000 CL30",
    ],
    [
      "Thermalright Peerless Assassin 120 SE 66.17 CFM CPU Cooler",
      "Thermalright Peerless Assassin 120 SE",
    ],
    ["Corsair RM850x 850 W 80+ Gold Power Supply", "Corsair RM850x 850W"],
    ["Samsung 990 Pro 2 TB M.2-2280 PCIe 4.0 X4 NVME Solid State Drive", "Samsung 990 Pro 2TB"],
    [
      "One Two Three Four Five Six Seven Eight Nine Ten Eleven",
      "One Two Three Four Five Six Seven Eight Nine",
    ],
  ])("%s", (name, expected) => {
    expect(pcppQuery(name)).toBe(expected);
  });
});

describe("catalogKey", () => {
  // Choice: equal. The extra words (clock, core count, "Processor") are filler that pcppQuery
  // cuts, so the PCPartPicker spelling and a hand-typed short name dedupe to one catalog entry.
  it("treats spec filler as the same product", () => {
    expect(catalogKey("AMD Ryzen 7 9800X3D 4.7 GHz 8-Core Processor")).toBe(
      catalogKey("AMD Ryzen 7 9800X3D"),
    );
  });
  it("keeps different products apart", () => {
    expect(catalogKey("AMD Ryzen 7 9800X3D")).not.toBe(catalogKey("AMD Ryzen 7 7800X3D"));
  });
  it("ignores case and punctuation", () => {
    expect(catalogKey("amd ryzen 7 9800x 3d")).toBe(catalogKey("AMD Ryzen 7 9800X3D"));
  });
});

describe("hostOf / slugText", () => {
  it("hostOf lowercases and drops www", () => {
    expect(hostOf("https://WWW.PCDiga.com/x?y=1")).toBe("pcdiga.com");
    expect(hostOf("http://shop.example.pt/")).toBe("shop.example.pt");
  });
  // The existing helper returns "" (not null) when there is no web host.
  it.each(["javascript:alert(1)", "file:///etc/passwd", "not a url", ""])(
    "hostOf(%j) is empty",
    (u) => {
      expect(hostOf(u)).toBe("");
    },
  );
  it("slugText turns the path into words", () => {
    expect(slugText("https://x.pt/p/amd-ryzen-7_9800x3d.html")).toBe("p amd ryzen 7 9800x3d");
    expect(slugText("https://x.pt/caf%C3%A9-bar")).toBe("café bar");
  });
  it("slugText tolerates non-web URLs", () => {
    expect(slugText("javascript:void(0)")).toBe("void(0)");
    expect(slugText("file:///tmp/some-file.txt")).toBe("tmp some file txt");
  });
});
