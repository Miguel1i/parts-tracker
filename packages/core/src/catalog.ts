/** Catalog helpers: PCPartPicker list import and the dedupe key for catalog entries. */
import { compact, normalizeTitle } from "./match/text";
import { parsePrice } from "./price";

export type PcppItem = { category: string; name: string; priceEur: number | null; url?: string };

const CATEGORIES = [
  "CPU Cooler",
  "CPU",
  "Motherboard",
  "Memory",
  "Storage",
  "Video Card",
  "Case Fan",
  "Case Accessory",
  "Case",
  "Power Supply",
  "Operating System",
  "Monitor",
  "Optical Drive",
  "Sound Card",
  "Wired Network Adapter",
  "Wireless Network Adapter",
  "Fan Controller",
  "Thermal Compound",
  "Expansion Card",
  "Keyboard",
  "Mouse",
  "Headphones",
  "Speakers",
  "Webcam",
  "UPS",
];

const PLAIN_LINE = new RegExp(`^(${CATEGORIES.join("|")})\\s*:?\\s+(.+)$`, "i");
const LINK = /\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/g;
const EUR_PRICE = /€\s?(\d[\d.,]*)/;
const TRAILING_PRICE = /\s*\(?[€$£]\s?\d[\d.,]*.*$/;

/** Only a euro amount counts; `$`/`£` prices are not converted. */
function eurPrice(text: string): number | null {
  const m = EUR_PRICE.exec(text);
  return m ? parsePrice(m[1]) : null;
}

/**
 * Parses a PCPartPicker list pasted as Markdown (`**CPU** | [name](url) | € 123,45`) or as
 * plain text / a copied table (`CPU  AMD Ryzen 7 9800X3D  €449,00  Buy`).
 * Headers, totals, blank and unrecognised lines are skipped.
 */
export function parsePcpp(text: string): PcppItem[] {
  const items: PcppItem[] = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || /generated by pcpartpicker/i.test(line)) continue;

    if (line.includes("|")) {
      const cells = line.replace(/^\|/, "").split("|");
      const category = (cells[0] ?? "").replace(/[*_]/g, "").trim();
      const link = [...line.matchAll(LINK)].find((m) => !/^buy$/i.test(m[1]!.trim()));
      if (!category || !link) continue; // header, separator, totals
      items.push({
        category,
        name: link[1]!.trim(),
        priceEur: eurPrice(line),
        url: link[2]!,
      });
      continue;
    }

    const m = PLAIN_LINE.exec(line);
    if (!m) continue;
    const name = m[2]!
      .replace(TRAILING_PRICE, "")
      .replace(/\s+Buy\s*$/i, "")
      .trim();
    if (!name) continue;
    items.push({ category: m[1]!, name, priceEur: eurPrice(line) });
  }
  return items;
}

/** Spec words that start the "filler" tail of a PCPartPicker part name. */
const CUT =
  /\s+(?:\d+(?:\.\d+)?\s?(?:GHz|CFM)|\d+-Core|M\.2|ATX|PCIe|80\+|Processor|Memory|Video Card|CPU Cooler|Motherboard|Solid State Drive|Power Supply|Case)(?![A-Za-z]).*$/i;

/** A PCPartPicker part name without parentheses and without its spec tail. */
function coreName(name: string): string {
  return name
    .replace(/\(.*?\)/g, "")
    .replace(/(\d)\s+(GB|TB|W)\b/gi, "$1$2")
    .replace(CUT, "")
    .trim();
}

/** Search query for a PCPartPicker part name: the core name, at most 9 words. */
export function pcppQuery(name: string): string {
  return coreName(name).split(/\s+/).slice(0, 9).join(" ") || name;
}

/**
 * Dedupe key: two names with the same core name denote the same catalog product. Unlike the
 * search query it isn't truncated, so variant words late in a long name (Ti, 16GB, OC…) still
 * tell products apart.
 */
export function catalogKey(name: string): string {
  return compact(normalizeTitle(coreName(name) || name));
}
