/** Builds a case-insensitive regex that matches any entry as a whole word. */
export function wordsRegex(words: readonly string[], flags = "i"): RegExp {
  return new RegExp(`(?<![a-z0-9])(?:${words.join("|")})(?![a-z0-9])`, flags);
}
